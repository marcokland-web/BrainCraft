// Platzhalter [NAME] aus gescannten Texten: Name einsetzen oder samt Komma weglassen
export function fillName(text: string, name: string) {
  if (name) return text.replaceAll('[NAME]', () => name)
  // Ohne Namen: „[NAME], was …“ → „Was …“, „Gut, [NAME]!“ → „Gut!“
  const out = text.replace(/^\s*\[NAME\]\s*,?\s*/, '').replace(/,?\s*\[NAME\]/g, '')
  return out.charAt(0).toUpperCase() + out.slice(1)
}

